# Database
# https://docs.djangoproject.com/en/5.2/ref/settings/#databases

if "test" in sys.argv:
    DATABASES = {
        'default': {
            'ENGINE': 'django.db.backends.sqlite3',
            'NAME': BASE_DIR / 'test_db.sqlite3',
        }
    }
else:
    DATABASE_URL = os.getenv("DATABASE_URL")
    if DATABASE_URL:
        parsed_database_url = urlparse(DATABASE_URL)
        if parsed_database_url.scheme.startswith("sqlite"):
            database_name = parsed_database_url.path.lstrip("/")
            DATABASES = {
                "default": {
                    "ENGINE": "django.db.backends.sqlite3",
                    "NAME": database_name or BASE_DIR / "db.sqlite3",
                }
            }
        else:
            DATABASES = {
                "default": {
                    "ENGINE": "django.db.backends.postgresql",
                    "NAME": parsed_database_url.path.lstrip("/"),
                    "USER": parsed_database_url.username,
                    "PASSWORD": parsed_database_url.password,
                    "HOST": parsed_database_url.hostname,
                    "PORT": parsed_database_url.port or 5432,
                    "OPTIONS": dict(parse_qsl(parsed_database_url.query)),
                }
            }
    else:
        DATABASES = {
            "default": {
                "ENGINE": "django.db.backends.sqlite3",
                "NAME": BASE_DIR / "db.sqlite3",
            }
        }

